use std::collections::BTreeMap;
use std::ffi::OsString;
use std::fs;
use std::path::{Path, PathBuf};

use sill::Environment;

use super::{GitAnswer, Pairing, compose, compose_hooks, declare};

const SYSTEM_CONFIG: &str = "/fixture/system.gitconfig";

/// One scratch Git directory, removed again when the test that made it ends.
struct Scratch(PathBuf);

impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

fn scratch(label: &str) -> Scratch {
    let root = std::env::temp_dir().join(format!(
        "spice-git-shadow-{label}-{}-{}",
        std::process::id(),
        uuid::Uuid::new_v4()
    ));
    fs::create_dir(&root).expect("scratch Git directory creates");
    Scratch(root)
}

/// Git as one worktree on `branch` with its own Git directory answers it.
///
/// Every other query reports nothing, as Git does for an unset key, and every
/// query records the environment it was asked under.
fn worktree<'a>(
    branch: &'a str,
    git_dir: &'a Path,
    merge: Option<&'a str>,
    asked: &'a mut Vec<BTreeMap<OsString, OsString>>,
) -> impl FnMut(&[&str], &BTreeMap<OsString, OsString>) -> GitAnswer + 'a {
    move |arguments, environment| {
        asked.push(environment.clone());
        let merge_key = format!("branch.{branch}.merge");
        Ok(match arguments {
            ["symbolic-ref", "--quiet", "--short", "HEAD"] => Some(branch.to_owned()),
            ["rev-parse", "--absolute-git-dir"] => Some(git_dir.display().to_string()),
            ["config", "--system", "--edit"] => Some(SYSTEM_CONFIG.to_owned()),
            ["config", "--get", key] if *key == merge_key => merge.map(str::to_owned),
            _ => None,
        })
    }
}

fn value<'a>(environment: &'a Environment, key: &str) -> Option<&'a str> {
    environment
        .entries()
        .iter()
        .find(|(name, _)| name == key)
        .and_then(|(_, value)| value.to_str())
}

/// The command-scope pairs the composed environment carries, in index order.
fn command_scope(environment: &Environment) -> Vec<(String, String)> {
    let count = value(environment, "GIT_CONFIG_COUNT").map_or(0, |count| {
        count.parse::<usize>().expect("GIT_CONFIG_COUNT is a count")
    });
    (0..count)
        .map(|index| {
            let pair = |prefix: &str| {
                value(environment, &format!("{prefix}{index}"))
                    .expect("every counted pair is present")
                    .to_owned()
            };
            (pair("GIT_CONFIG_KEY_"), pair("GIT_CONFIG_VALUE_"))
        })
        .collect()
}

/// The shadow lands in the Git directory `--absolute-git-dir` names, which is
/// the per-worktree one in a linked worktree, and becomes the system scope.
#[test]
fn the_shadow_is_published_in_the_worktree_git_directory_as_system_scope() {
    let scratch = scratch("publish");
    let mut asked = Vec::new();

    let composed = compose(
        Environment::new([("PATH", "/usr/bin")]).expect("base"),
        worktree("lane-bytes", &scratch.0, None, &mut asked),
    )
    .expect("the shadow composes");

    let published = scratch.0.join("agent.gitconfig");
    assert_eq!(
        value(&composed, "GIT_CONFIG_SYSTEM"),
        Some(published.to_str().expect("UTF-8 scratch path"))
    );
    assert_eq!(
        fs::read_to_string(&published).expect("the shadow was written"),
        concat!(
            "# Generated by spice for the per-process agent git shadow.\n",
            "[include]\n",
            "\tpath = /fixture/system.gitconfig\n",
            "[branch \"lane-bytes\"]\n",
            "\tmerge = refs/heads/lane-bytes\n",
        )
    );
    assert_eq!(value(&composed, "PATH"), Some("/usr/bin"));
    assert_eq!(
        command_scope(&composed),
        vec![("branch.lane-bytes.remote".to_owned(), ".".to_owned())]
    );
}

/// The true integration branch rides the final command scope, and Git is never
/// asked under a shadow the caller already inherited.
#[test]
fn the_true_merge_rides_the_command_scope_over_an_inherited_shadow() {
    let scratch = scratch("merge");
    let mut asked = Vec::new();
    let base = Environment::new([
        ("PATH", "/usr/bin"),
        ("GIT_CONFIG_SYSTEM", "/inherited/shadow"),
        ("GIT_CONFIG_COUNT", "1"),
        ("GIT_CONFIG_KEY_0", "branch.lane.merge"),
        ("GIT_CONFIG_VALUE_0", "refs/heads/stale"),
    ])
    .expect("base");

    let composed = compose(
        base,
        worktree("lane", &scratch.0, Some("refs/heads/main"), &mut asked),
    )
    .expect("the shadow composes");

    assert_eq!(
        command_scope(&composed),
        vec![
            ("branch.lane.merge".to_owned(), "refs/heads/main".to_owned()),
            ("branch.lane.remote".to_owned(), ".".to_owned()),
        ]
    );
    assert!(!asked.is_empty());
    for environment in &asked {
        assert!(
            environment
                .keys()
                .all(|key| !key.to_string_lossy().starts_with("GIT_CONFIG")),
            "Git was asked under an inherited shadow: {environment:?}"
        );
    }
}

/// A detached head leaves the caller's environment exactly as it was.
#[test]
fn a_detached_head_composes_no_shadow() {
    let scratch = scratch("detached");
    let base = Environment::new([("PATH", "/usr/bin")]).expect("base");

    let composed = compose(base.clone(), |arguments, _| {
        Ok(match arguments {
            ["rev-parse", "--absolute-git-dir"] => Some(scratch.0.display().to_string()),
            _ => None,
        })
    })
    .expect("a detached head is not an error");

    assert_eq!(composed, base);
    assert!(!scratch.0.join("agent.gitconfig").exists());
}

/// A Git-valid double quote is escaped in the subsection and nowhere else.
#[test]
fn a_quoted_branch_is_escaped_only_in_its_subsection() {
    let scratch = scratch("quoted");
    let mut asked = Vec::new();

    compose(
        Environment::new([("PATH", "/usr/bin")]).expect("base"),
        worktree("lane-quo\"te", &scratch.0, None, &mut asked),
    )
    .expect("the shadow composes");

    let published =
        fs::read_to_string(scratch.0.join("agent.gitconfig")).expect("the shadow was written");
    assert!(published.contains("[branch \"lane-quo\\\"te\"]\n"));
    assert!(published.contains("\tmerge = refs/heads/lane-quo\"te\n"));
}

/// Publishing twice leaves the byte-identical file the first run wrote.
#[test]
fn a_second_publication_rewrites_nothing() {
    let scratch = scratch("idempotent");
    let published = scratch.0.join("agent.gitconfig");
    let mut asked = Vec::new();
    let base = Environment::new([("PATH", "/usr/bin")]).expect("base");

    compose(base.clone(), worktree("lane", &scratch.0, None, &mut asked))
        .expect("the first shadow composes");
    let first = fs::metadata(&published).expect("the first run published");
    compose(base, worktree("lane", &scratch.0, None, &mut asked))
        .expect("the second shadow composes");
    let second = fs::metadata(&published).expect("the shadow survives");

    assert_eq!(
        first.modified().expect("modification time"),
        second.modified().expect("modification time"),
        "the second run republished identical bytes"
    );
}

/// The pairing `lane` reads when its configuration holds `remote` and `merge`.
fn declared(remote: Option<&str>, merge: Option<&str>) -> Result<Option<Pairing>, super::Error> {
    declare("lane", |arguments| {
        Ok(match arguments {
            ["config", "--get", "branch.lane.remote"] => remote.map(str::to_owned),
            ["config", "--get", "branch.lane.merge"] => merge.map(str::to_owned),
            other => panic!("unexpected Git query {other:?}"),
        })
    })
}

#[test]
fn a_dot_pairing_protects_the_local_branch_it_integrates_into() {
    let pairing = declared(Some("."), Some("refs/heads/main"))
        .expect("a whole pairing reads")
        .expect("the pairing is declared");

    assert!(pairing.is_local());
    assert_eq!(pairing.branch, "main");
    assert_eq!(pairing.reference(), "refs/heads/main");
}

#[test]
fn a_remote_pairing_names_its_remote_tracking_branch() {
    let pairing = declared(Some("upstream"), Some("refs/heads/trunk"))
        .expect("a whole pairing reads")
        .expect("the pairing is declared");

    assert!(!pairing.is_local());
    assert_eq!(pairing.reference(), "refs/remotes/upstream/trunk");
}

#[test]
fn only_a_branch_declaring_neither_half_is_untracked() {
    assert_eq!(declared(None, None).expect("nothing declared reads"), None);
    for (remote, merge) in [
        (Some("origin"), None),
        (None, Some("refs/heads/main")),
        (Some("origin"), Some("main")),
    ] {
        assert!(
            declared(remote, merge).is_err(),
            "remote {remote:?} with merge {merge:?} passed for a pairing"
        );
    }
}

/// One complete installed hook fixture and the conditional pairs it expects.
struct HookFixture {
    owner: PathBuf,
    launchers: PathBuf,
    config: PathBuf,
    exact: String,
    descendants: String,
    config_spelling: String,
}

fn hook_fixture(scratch: &Scratch, launchers: &[&str]) -> HookFixture {
    let owner = scratch.0.join("owner.git");
    let directory = scratch.0.join("git-hooks");
    let config = directory.join("config");
    fs::create_dir(&owner).expect("owner directory creates");
    fs::create_dir(&directory).expect("launcher directory creates");
    for launcher in launchers {
        fs::write(directory.join(launcher), "#!/bin/sh\n").expect("launcher writes");
    }
    let launcher_spelling =
        crate::repository::git_spelling(&directory).expect("launcher directory has a Git spelling");
    fs::write(
        &config,
        format!("[core]\n\thooksPath = \"{launcher_spelling}\"\n"),
    )
    .expect("config writes");
    let canonical_owner = fs::canonicalize(&owner).expect("owner canonicalizes");
    let owner_spelling =
        crate::repository::git_spelling(&canonical_owner).expect("owner has a Git spelling");
    let config_spelling = crate::repository::git_spelling(&config)
        .expect("config has a Git spelling")
        .into_owned();
    HookFixture {
        owner,
        launchers: directory,
        config,
        exact: format!("{}{}.path", super::HOOK_INCLUDE_PREFIX, owner_spelling),
        descendants: format!("{}{}/**.path", super::HOOK_INCLUDE_PREFIX, owner_spelling),
        config_spelling,
    }
}

const LAUNCHERS: [&str; 3] = ["pre-commit", "commit-msg", "reference-transaction"];

fn compose_fixture(base: Environment, fixture: &HookFixture) -> Environment {
    compose_hooks(base, &fixture.owner, &fixture.launchers, &fixture.config)
        .expect("the hooks includes compose")
}

/// Hook activation is conditional on the owning Git directory. The owned
/// includes follow inherited pairs, which keep their order.
#[test]
fn the_owned_hook_includes_follow_inherited_pairs() {
    let scratch = scratch("hooks-pairs");
    let fixture = hook_fixture(&scratch, &LAUNCHERS);
    let pair = |key: &str, value: &str| (key.to_owned(), value.to_owned());
    for (label, inherited, expected_prefix) in [
        ("no pairs", vec![], vec![]),
        (
            "one foreign pair",
            vec![("user.name", "agent")],
            vec![pair("user.name", "agent")],
        ),
    ] {
        let mut entries = vec![("PATH".to_owned(), "/usr/bin".to_owned())];
        entries.push(("GIT_CONFIG_COUNT".to_owned(), inherited.len().to_string()));
        for (index, (key, value)) in inherited.iter().enumerate() {
            entries.push((format!("GIT_CONFIG_KEY_{index}"), (*key).to_owned()));
            entries.push((format!("GIT_CONFIG_VALUE_{index}"), (*value).to_owned()));
        }
        let mut expected = expected_prefix;
        expected.push(pair(&fixture.exact, &fixture.config_spelling));
        expected.push(pair(&fixture.descendants, &fixture.config_spelling));

        let composed = compose_fixture(Environment::new(entries).expect("base"), &fixture);

        assert_eq!(command_scope(&composed), expected, "{label}");
        assert_eq!(value(&composed, "PATH"), Some("/usr/bin"), "{label}");
    }
}

/// Reapplying hook composition, even after the upstream pairs exist, preserves
/// the byte-identical environment and each pair's position.
#[test]
fn hook_composition_is_idempotent_after_upstream_composition() {
    let scratch = scratch("hooks-idempotent");
    let fixture = hook_fixture(&scratch, &LAUNCHERS);
    let mut asked = Vec::new();
    let hooked = compose_fixture(
        Environment::new([("PATH", "/usr/bin")]).expect("base"),
        &fixture,
    );
    let composed = compose(
        hooked,
        worktree("lane", &scratch.0, Some("refs/heads/main"), &mut asked),
    )
    .expect("the upstream shadow composes");

    assert_eq!(compose_fixture(composed.clone(), &fixture), composed);
}

#[test]
fn gitdir_conditions_escape_path_globs_and_pattern_escapes() {
    assert_eq!(
        super::gitdir_pattern("/owner/[lane]*?/back\\slash"),
        r"/owner/\[lane\]\*\?/back\\slash"
    );

    let scratch = scratch("hooks-pattern");
    let fixture = hook_fixture(&scratch, &LAUNCHERS);
    let owner = scratch.0.join("owner[*?].git");
    fs::create_dir(&owner).expect("patterned owner creates");
    let composed = compose_hooks(
        Environment::new([("PATH", "/usr/bin")]).expect("base"),
        &owner,
        &fixture.launchers,
        &fixture.config,
    )
    .expect("patterned owner composes");
    let canonical = fs::canonicalize(owner).expect("patterned owner canonicalizes");
    let spelling = crate::repository::git_spelling(&canonical).expect("owner has Git spelling");
    let pattern = super::gitdir_pattern(&spelling);
    let pairs = command_scope(&composed);

    assert_eq!(
        pairs[0],
        (
            format!("{}{pattern}.path", super::HOOK_INCLUDE_PREFIX),
            fixture.config_spelling.clone()
        )
    );
    assert_eq!(
        pairs[1],
        (
            format!("{}{pattern}/**.path", super::HOOK_INCLUDE_PREFIX),
            fixture.config_spelling
        )
    );
}

/// A count Git would refuse, or a counted pair missing a half, is an error
/// naming the variable instead of a guess.
#[test]
fn a_malformed_command_scope_is_refused_naming_its_variable() {
    let scratch = scratch("hooks-malformed");
    let fixture = hook_fixture(&scratch, &LAUNCHERS);
    for (pairs, named) in [
        (vec![("GIT_CONFIG_COUNT", "two")], "GIT_CONFIG_COUNT"),
        (vec![("GIT_CONFIG_COUNT", "+1")], "GIT_CONFIG_COUNT"),
        (vec![("GIT_CONFIG_COUNT", "")], "GIT_CONFIG_COUNT"),
        (
            vec![
                ("GIT_CONFIG_COUNT", "2"),
                ("GIT_CONFIG_KEY_0", "user.name"),
                ("GIT_CONFIG_VALUE_0", "agent"),
                ("GIT_CONFIG_VALUE_1", "orphan"),
            ],
            "GIT_CONFIG_KEY_1",
        ),
        (
            vec![("GIT_CONFIG_COUNT", "1"), ("GIT_CONFIG_KEY_0", "user.name")],
            "GIT_CONFIG_VALUE_0",
        ),
    ] {
        let base = Environment::new(pairs.clone()).expect("base");

        let error = compose_hooks(base, &fixture.owner, &fixture.launchers, &fixture.config)
            .expect_err("a malformed scope is refused");

        assert!(
            error.to_string().contains(named),
            "{pairs:?} refused without naming {named}: {error}"
        );
    }
}

/// Without a complete installed asset set the caller's environment is
/// unchanged, so Git keeps whatever hooks configuration it natively has.
#[test]
fn an_incomplete_or_absent_hook_asset_set_composes_nothing() {
    let scratch = scratch("hooks-incomplete");
    let partial = hook_fixture(&scratch, &LAUNCHERS[..2]);
    let base = Environment::new([
        ("PATH", "/usr/bin"),
        ("GIT_CONFIG_COUNT", "1"),
        ("GIT_CONFIG_KEY_0", "user.name"),
        ("GIT_CONFIG_VALUE_0", "agent"),
    ])
    .expect("base");

    let composed = compose_hooks(
        base.clone(),
        &partial.owner,
        &partial.launchers,
        &partial.config,
    )
    .expect("partial launchers are not an error");
    assert_eq!(composed, base);

    fs::remove_file(&partial.config).expect("config removes");
    let composed = compose_hooks(
        base.clone(),
        &partial.owner,
        &partial.launchers,
        &partial.config,
    )
    .expect("missing config is not an error");
    assert_eq!(composed, base);
}

/// A config selecting any directory but the installed launchers is refused:
/// a copy would run its original's hooks and a move would run none.
#[test]
fn a_config_selecting_another_launcher_directory_is_refused() {
    let scratch = scratch("hooks-relocated");
    let fixture = hook_fixture(&scratch, &LAUNCHERS);
    let base = Environment::new([("PATH", "/usr/bin")]).expect("base");

    let copied = scratch.0.join("copied-hooks");
    fs::create_dir(&copied).expect("copy directory creates");
    for name in LAUNCHERS.iter().chain(&["config"]) {
        fs::copy(fixture.launchers.join(name), copied.join(name)).expect("asset copies");
    }
    compose_hooks(
        base.clone(),
        &fixture.owner,
        &copied,
        &copied.join("config"),
    )
    .expect_err("a copy selecting its original is refused");

    let moved = scratch.0.join("moved-hooks");
    fs::rename(&fixture.launchers, &moved).expect("launcher directory moves");
    compose_hooks(base, &fixture.owner, &moved, &moved.join("config"))
        .expect_err("a move selecting its vanished origin is refused");
}

/// The upstream shadow composed after the hook includes appends behind them,
/// so a lane carries both and neither moves the other's index.
#[test]
fn upstream_pairs_compose_behind_the_hook_includes() {
    let scratch = scratch("hooks-then-shadow");
    let fixture = hook_fixture(&scratch, &LAUNCHERS);
    let mut asked = Vec::new();
    let hooked = compose_fixture(
        Environment::new([("PATH", "/usr/bin")]).expect("base"),
        &fixture,
    );

    let composed = compose(
        hooked,
        worktree("lane", &scratch.0, Some("refs/heads/main"), &mut asked),
    )
    .expect("the shadow composes");

    assert_eq!(
        command_scope(&composed),
        vec![
            (fixture.exact, fixture.config_spelling.clone()),
            (fixture.descendants, fixture.config_spelling),
            ("branch.lane.merge".to_owned(), "refs/heads/main".to_owned()),
            ("branch.lane.remote".to_owned(), ".".to_owned()),
        ]
    );
}
